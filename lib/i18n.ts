export type TKey = keyof typeof T['fr'];

export function tFn(langue: Langue, key: TKey): string {
  const dict = T[langue] ?? T.fr;
  return (dict as Record<string, string>)[key]
    ?? (T.fr as Record<string, string>)[key]
    ?? String(key);
}

export function getStoredLangue(): Langue {
  if (typeof window === 'undefined') return 'fr';
  const v = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return (v === 'fr' || v === 'es' || v === 'en') ? v : 'fr';
}

export function storeLangue(langue: Langue): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem(LANGUAGE_STORAGE_KEY, langue);
  window.dispatchEvent(new CustomEvent(LANGUAGE_CHANGE_EVENT, { detail: langue }));
}
